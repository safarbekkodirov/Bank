#!/usr/bin/env bash
# ==========================================================================
#  Mini Bank — PHASE 10B : PostgreSQL BACKUP scripti
# ==========================================================================
#  MAKSAT
#  Biznes маалыматын (users, accounts, transactions) PostgreSQL'дин
#  өзүнүн куралдары (pg_dump) менен коюп, аны кайта окулатын
#  (.dump) файлына жазыу.
#
#  ФОРМАТ: custom format (-Fc) — PostgreSQL'дин СУПЕРЧЕТКЕСИНДИК формат.
#     Анда неге:
#       • КОМПРЕССИЯЛАН (кичи, тез ташылга).
#       • КАТТАРЫ ТАРТИБИНДЕ калгана алат (pg_restore -j — тез).
#       • АВТОМАТИК ҢАД: pg_restore БИТТИК ТАБЛИЦА БОЛБОЙ, тамгалар
#         (ACL/comment) менен калгана алат.
#       • Текшеруү БОЛУТ: `pg_restore --list` — файлдын ичинде
#         эмне бар экенин көрсөтөт (PHASE 10B §10).
#
#  🔴 КООПСУЗДУК (PHASE 10B §17)
#     • Пароль ЭЧ КАЧАН командaga жазылбайт.
#     • Пароль ЭЧ КАЧАН калга коюлбайт (pg_dump аны таламайт).
#     • Пароль ЭЧ КАЧАН экранга чыкпайт.
#     • Биз контейнер ИЧИНКИ розетка (unix socket) аркылуу
#       улашабыз — Docker'дун postgres образы локалдык
#       туташууну `trust` (сырсиз) кылып жаратат.
#     • Конфигурация .env файлынан окулат (pwd_to_env).
#
#  КАЧЫНЧА УЛУШУ:
#     ./scripts/backup-db.sh              -> backups/minibank_YYYYmmdd_HHMMSS.dump
#     ./scripts/backup-db.sh myfile.dump  -> белгилеген ат
#
#  КАЙТЫШ:
#     0 — ийгилик
#     1 — ээ чыкпады (маалымат/папка/көрсөткөн файл)
#     2 — контейнер иштемейт / улашылмайт
#     3 — pg_dump устунан ката
# ==========================================================================

set -euo pipefail

# --- Биз буйрукка кандай болбосун, ҲӘРГАШ ЭМИН ПРОЕКТ ДЕРЕЖЕСИНДЕ БОЛУШУ
#     КЕРЕК. Эгер башка папкадан чалышты, .env табылмай -> тушуктүү
#     ката бербир (жалгаптын узактында «backup» тапмай калмак).
SCRIPT_DIR="$(cd -- "$(dirname -- "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_DIR="$(cd -- "${SCRIPT_DIR}/.." && pwd)"

cd "${PROJECT_DIR}"

# ---- ЧЫГАРЫЛУШ ЖОЛДОРУ ----
BACKUP_DIR="${PROJECT_DIR}/backups"

log()  { printf '[backup] %s\n' "$*"; }
fail() { printf '[backup] ХАТА: %s\n' "$*" >&2; }

# ==========================================================================
#  1) .env ДИ ОКУУ
# ==========================================================================
#  🧡 ЭМНЕ ОШУНДАЙ?
#  Проекттиң .env файлы — бирден-бир чыныгы конфигурация. Биз аны
#  Spring Boot киби Docker Compose киби ОКУЙДУ. Скрипт терек артындан
#  эмес, ОЛУЧТАН ҺЕСИМДЕРДЕН окшул чыныгы файлды окuyт — башкача болсо,
#  биз ТУРГУБЫЗДУ башка (эс тест) базага которуп ыйлар эле.
# ==========================================================================
ENV_FILE="${PROJECT_DIR}/.env"
if [[ ! -f "${ENV_FILE}" ]]; then
    fail ".env табылмады: ${ENV_FILE}"
    fail "Үлгүсүн көчүрүп, сырлары толуклаг: cp .env.example .env"
    exit 1
fi

set -a
# shellcheck disable=SC1090
source "${ENV_FILE}"
set +a

DB_NAME="${POSTGRES_DB:-}"
DB_USER="${POSTGRES_USER:-}"

if [[ -z "${DB_NAME}" || -z "${DB_USER}" ]]; then
    fail ".env ичинде POSTGRES_DB жана POSTGRES_USER КЕРЕК."
    exit 1
fi

# ==========================================================================
#  2) ЧЫГАРЫЛУШ ПАПКАСЫН ТАЙЯРЛАШ
# ==========================================================================
#  🔴 ИШЕК БЕРИШ: папка жазылмаса, pg_dump «сын» ириш болмак эле —
#     ал чыгып кеткен өткөн катта (pipe) ээсине эмес, КОНТЕЙНЕРГЕ
#     бара эле («Error writing to output: No such file or directory»).
#     Ошондуктан БИЗ ЭМНЕ КЕТАРЫБЫЗДЫ АЛДЫН ТЕКШЕРЕБИЗ.
# ==========================================================================
mkdir -p "${BACKUP_DIR}"
if [[ ! -w "${BACKUP_DIR}" ]]; then
    fail "Backup папкасы ЖАЗЫЛМАЙТ: ${BACKUP_DIR}"
    exit 1
fi

TIMESTAMP="$(date +%Y%m%d_%H%M%S)"
if [[ $# -ge 1 && -n "${1:-}" ]]; then
    TARGET="${BACKUP_DIR}/$1"
else
    TARGET="${BACKUP_DIR}/${DB_NAME}_${TIMESTAMP}.dump"
fi

# ==========================================================================
#  2b) МАКЕТ ЖАЗЫЛАТЫГЫНА ТЕКШЕРҮҮ  (авиациянын өнүгүшүнөн КИЙИН)
# ==========================================================================
#  🧡 ЭМНЕ БУЛ КЕРЕК?
#  `> "${TARGET}"` кавышын колдонгондо, папка жок/жазылмаса
#  КАТА БУЙРУККА УЧУП, docker exec ВООБЩЕ ИШТЕМЕЙТ. Бизге болгон
#  эки ката:
#     1) Катанын себеби көрүнбөй (кайсы папка дээр);
#     2) pg_dump катасынын кабары жалгаш жоқ болуп кетет.
#  Ошондуктан биз АЛДЫН ТЕКШЕРЕБИЗ — түз, тушуктүү ката беребиз.
# ==========================================================================
TARGET_DIR="$(dirname -- "${TARGET}")"
if [[ ! -d "${TARGET_DIR}" ]]; then
    fail "Макет папкасы ЖОК: ${TARGET_DIR}"
    exit 1
fi

if [[ -e "${TARGET}" && -d "${TARGET}" ]]; then
    fail "Макет — бул ПАПКА (файл эмес): ${TARGET}"
    exit 1
fi

# touch менен чыныгы жазныкты текшеребиз (укум тизими каталары —
# «Permission denied» жана башка — ошол жерден чыгат).
if ! ( : > "${TARGET}" ) 2>/dev/null; then
    fail "Бу жерге ЖАЗЫЛМАЙТ: ${TARGET}"
    fail "Папканын укумун текшериңиз:  ls -ld ${TARGET_DIR}"
    exit 1
fi
rm -f "${TARGET}"

# ==========================================================================
#  3) КОНТЕЙНЕРДИ ТАБУУ
# ==========================================================================
#  🧡 ЭМНЕ «hardcode» КЫЛБАЙТЫ?
#  Контейнерди атын жазсак («minibank-postgres»), бир күнү compose.yml'де
#  аты өзгөрсө, скрипт ЖАШЫРЫН оңбок калар эле. Ошондуктан аны
#  Docker'дан СУРАП алабыз: compose'теги кызматтын id'си.
# ==========================================================================
if ! command -v docker >/dev/null 2>&1; then
    fail "docker табылмады."
    exit 2
fi

if ! docker info >/dev/null 2>&1; then
    fail "Docker иштемийт (daemon ушул убакта табылмады)."
    exit 2
fi

CONTAINER_ID="$(docker compose ps -q postgres 2>/dev/null || true)"

if [[ -z "${CONTAINER_ID}" ]]; then
    fail "«postgres» кызматы иштеп жаткан контейнер табылмады."
    fail "Адегенде:  docker compose up -d"
    exit 2
fi

CONTAINER_NAME="$(docker inspect -f '{{.Name}}' "${CONTAINER_ID}" | sed 's|^/||')"

# ДАЯР ЭМЕС болсо: убакыт күтпей, түз айтабыз. (pg_dump «connect to
# server failed» деп узак ката берет — биз аны кыска кылабыз.)
RUNNING="$(docker inspect -f '{{.State.Running}}' "${CONTAINER_ID}" 2>/dev/null || echo false)"
if [[ "${RUNNING}" != "true" ]]; then
    fail "PostgreSQL контейнери иштемийт (${CONTAINER_NAME})."
    fail "Адегенде:  docker compose up -d"
    exit 2
fi

# ==========================================================================
#  4) УЛАШУ ОНОК БОЛГУНО ТЕКШЕРҮҮ
# ==========================================================================
#  🧡 pg_dump'ды иштетүүнөн АЛДЫН базага кошулуш мүмкүндүгүн
#  билгибиз керек. Болбосон, биз ТОЛУК файлды 0 байт менен
#  «ийгилик» деп жазып, кийин «backup бар» деп ыйнап берер эле —
#  ал эң ХУЮШ абал: аварылган backup ЭМЕС, бирок аныкча көрүнөт.
# ==========================================================================
if ! docker exec "${CONTAINER_ID}" psql -U "${DB_USER}" -d "${DB_NAME}" -c 'SELECT 1' >/dev/null 2>&1; then
    fail "Маалымат базасына кошулуш мүмкүн болду: ${DB_NAME}"
    fail "Контейнер даяр болмай калган болушу мүмкүн. 5 секунд күтип, дагы сынап көрүңүз."
    exit 2
fi

log "База: ${DB_NAME}  →  Контейнер: ${CONTAINER_NAME}"
log "Макет: ${TARGET}"

# ==========================================================================
#  5) pg_dump
# ==========================================================================
#  🧡 ЭМНЕ stdin/stdout АРКЫЛУУ?
#  Дампты контейнерден СЫРТКА, биз файлга жазып алабыз:
#      docker exec ... pg_dump -Fc  >  файл
#  Пароль буйрукта ЖОК; pg_dump аны таламайт (локалдык socket = trust).
#
#  --no-owner / --no-privileges : кээде калгана келген базада ээси
#      башка колдонуучу болсо «permission denied for owner» катасы
#      чыгат. Бул флагдар аны алдын алат.
# ==========================================================================
if docker exec "${CONTAINER_ID}" \
        pg_dump -U "${DB_USER}" -d "${DB_NAME}" \
        --format=custom \
        --no-owner \
        --no-privileges \
        > "${TARGET}"; then
    log "pg_dump аяктады."
else
    rc=$?
    fail "pg_dump КАТАСЫ (код ${rc}). Бүтүн файл өчүрилөт."
    rm -f "${TARGET}"
    exit 3
fi

# ==========================================================================
#  6) НЕМИНЕ ЧЫГАРГАНЫБЫЗДЫ ТЕКШЕРҮҮ (PHASE 10B §10)
# ==========================================================================
#  🧡 «pg_dump ийгиликтүү» ДЕГЕН СӨЗ — «файл бар» дегенди билдирбейт.
#  0 байттук (ошак) файл — бул ЖАЛГАН backup. Ошонду текшеребиз.
# ==========================================================================
if [[ ! -s "${TARGET}" ]]; then
    fail "Backup файлы БОШ (0 байт) — бул ийгилик эмес."
    rm -f "${TARGET}"
    exit 3
fi

SIZE="$(wc -c < "${TARGET}" | tr -d ' ')"
log "Файл: ${TARGET} (${SIZE} байт)"

# Таблицалар бош болсо да, файл ТОЛУК болушу керек (pg_dump СКЕМА +
# Flyway журналы + sequence — булар да dump'ка кирет).
if [[ "${SIZE}" -lt 1024 ]]; then
    fail "Backup өтө чыдак (${SIZE} байт). Бу ыктымалдык — тек текшер."
    exit 3
fi

log "ЫЙГИЛИК: backup жасалды → ${TARGET}"
echo "${TARGET}"