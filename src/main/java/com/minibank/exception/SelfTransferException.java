package com.minibank.exception;

/**
 * 409 CONFLICT — колдонуучу ӨЗ ЭСЕБИНЕ ӨЗҮН КОТУРМОКЧУ.
 *
 * 🧠 БИЗМУН ЭМНЕГЕ 409 (Conflict), ЭМЕС 400 (Bad Request)?
 *     400 = «сен БУРУШ СҮРОМУ КЫЛДЫҢ» (маалыматын туура эмес жаздың).
 *     409 = «сен БУРУШ СҮРОМУ КЫЛДЫҢ, бирок аны ИШКЕ КОЛДОНБАЙТ»:
 *           эсеп номуру ЧЫНЫГЫ, колдонуучу ЧЫНЫГЫ, сумма ЧЫНЫГЫ —
 *           бирок «сен өзүңдүн эсебиңе өзүң которуйт» деген амал
 *           БИЗДЕ ЖОК. Бул абалдын өзүнө «сен жаңы эсеп ач, кийин
 *           котору» деп оңдөп болот — демек кайта аракет кылууга БОЛЕТ.
 *
 * 🧠 ЭМНЕ БУЛ ЧЫНДА КЫЗЫЛ ТАЛАБА (чыныгы ката)?
 *     Эгер биз «А → А» деп унутуп, аны адегенде аткарып алса:
 *         1. A депет 300
 *         2. A кредит 300
 *         3. A = 1000 (баланс өзгөрбөйт — көзүнө көрүнбөйт!)
 *         4. Бирок ЖУРНАЛДА «TRANSFER_OUT 300» ЖАНА «TRANSFER_IN 300»
 *            деп ЭКИ жазуу пайда болот
 * *      Демек акча «кайда кетти?» деп суроо чыгат, анын жообу ЖОК —
 *         эсептеги саны туура, журналда чындап эки операция.
 *     Дагы куртуу: эгер биз эки башка эсепке өтүп, эки account'ту
 *     эле кулопка менен алып, эки жолу lock кылсак — бир эле
 *     PostgreSQL'деги жазууну ЕКИНЧИ ЖОЛ lock кылууга аракет кылып,
 *     ӨЗ БАШАБЫНА КУТУП КАЛЫП, DEADLOCK таанып (мыкейүү жарайт).
 *     Ошондуктан 409'ду АЛГАЧТАЙ, кулопка алуудан ТҮРҮН текшеребиз.
 *
 * 🔴 БААРЫ ӨЗГӨРҮЛБӨЙТ: баланс, журнал — эч нерсэ. Биз балансты
 *    «дебитлеп, кредитлеп, бүгүн өзүнө кайтарып» деп ойлоп чыгарабыз.
 */
public class SelfTransferException extends RuntimeException {

    public SelfTransferException(String message) {
        super(message);
    }

    /** Эсеп номуру менен — колдонуучуга түшүнүктүү бүт жазуу. */
    public static SelfTransferException of(String accountNumber) {
        return new SelfTransferException(
                "Cannot transfer to the same account: " + accountNumber);
    }
}