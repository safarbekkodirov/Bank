package com.minibank.entity;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.Table;

/**
 * users таблицасынын Java көрүнүшү.
 *
 * Entity = Java классы  <-->  DB таблицасынын бир жазуусу.
 * Аннотациялар (@Entity, @Column) JPAга "кайсы клас кайсы колонкага туура келет"
 * деп айтат.
 *
 * ⚠️ БУЛ КЛАСС API ГА ЧЫГАРЫЛБАЙТ (Entity ≠ DTO эрежеси). Controllerге
 * UserResponse (dto) келедь, User эмес.
 *
 * Hibernate ddl-auto=validate болгондуктан: бул класстын маалыматтары
 * базадагы таблица менен БИРДЕЙ болушу керек. Болбосо колдонмо иштегенде
 * "schema validation failed" ката берет. Бул — ыңгайлуу: Java менен SQL
 * ар дайым бири-бирине каршы текшерүүлөт.
 */
@Entity
@Table(name = "users")
public class User extends BaseEntity {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    // DB: BIGINT GENERATED BY DEFAULT AS IDENTITY
    private Long id;

    @Column(name = "full_name", nullable = false, length = 150)
    private String fullName;

    @Column(name = "email", nullable = false, unique = true, length = 255)
    // DB: CHECK (email = lower(email))  -> чоң тамга биз КАЙТАРАМБЫЗ
    private String email;

    @Column(name = "password_hash", nullable = false, length = 255)
    // 🔴 БУЛ ТААЛАА ПАРОЛЬ ЕМЕС, АНЫН ХЭШИН САКТАЙТ. Пароль өзү эч качан
    // базага жазылбайт жана эч качан API аркылуу кайтарылбайт.
    private String passwordHash;

    @Enumerated(EnumType.STRING)   // ← ЭЧ КАЧАН ORDINAL ЭМЕС (Role.java кара)
    @Column(name = "role", nullable = false, length = 20)
    private Role role;

    protected User() {
        // JPA үчүн: Hibernate объектини өзү түзөт
    }

    public User(String fullName, String email, String passwordHash, Role role) {
        this.fullName = fullName;
        this.email = email;
        this.passwordHash = passwordHash;
        this.role = role;
    }

    public Long getId() {
        return id;
    }

    public String getFullName() {
        return fullName;
    }

    public String getEmail() {
        return email;
    }

    public String getPasswordHash() {
        return passwordHash;
    }

    public Role getRole() {
        return role;
    }
}
