package com.minibank.entity;

import java.math.BigDecimal;
import java.time.Instant;

import org.springframework.data.annotation.CreatedDate;
import org.springframework.data.jpa.domain.support.AuditingEntityListener;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.EntityListeners;
import jakarta.persistence.EnumType;
import jakarta.persistence.Enumerated;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

/**
 * transactions таблицасынын Java көрүнүшү — АКЧА ОПЕРАЦИЯСЫНЫН ЖУРНАЛЫ.
 *
 * БАЙЛАНЫШ:
 *     accounts 1 ──────< transactions
 *   (эсепте канча көп операция болгонун айтат; FK: account_id -> accounts.id)
 *
 * 🧡 БИЗДИН ГЛАВНОЙ ЭРЕЖЕ — БУЛ ТАБАЛБА ЫШАЙТ:
 *     • Эсепке бир операция = бир жазуу. ЭЧ КАЧАН өзгөртүлбөйт, ӨЧҮРҮЛБӨЙТ.
 *       (Бу «append-only ledger» — чыныгы банкта да ошолулош.)
 *     • Сутка ичинде жасалган операциялар өзгөрбөйт, тек ҮСТӨЛӨТ.
 *     • Демек @Version (optimistic locking) БУГА КОЛДОНУЛБАЙТ —
 *       эгер колдонсок, эстен кээ бир «эски» жазууну жаңыртууга
 *       аракет кылганда, колдонуучунун ТАРИХИ жарылып кетмекчи.
 *       Биз тек окуу үчүн жазабыз — балансты өзгөрткөн эмес.
 *
 * 🔴 ЭҢ МААНИЛҮҮ ЧЕЧИМ — БИЗ BaseEntity'ге МУРАСТЫК ЭМЕС:
 *     BaseEntity эки таалду берет: created_at ЖАНА updated_at.
 *     Бирок transactions таблицасында updated_at колонкасы ЖОК
 *     (каро: V1__init.sql) — анткени жазуу өзгөртүлбөйт, убакыт
 *     белгиси бир гана керек.
 *     Эгер мураст алсак, Hibernate `ddl-auto=validate` колдонумду
 *     ИШТЕТПЕЙ ТОКТОТТУ болмок ("missing column [updated_at]").
 *     Ошондуктан биз BaseEntity'дин МИНИМУМУН (@CreatedDate + аудит
 *     чыпкасы) кайталап, кол менен алабыз.
 *
 * 🧡 amount > 0, БИРОК ТЕРС ЭМЕС (мааниси 15-бөлүм):
 *     WITHDRAW 200 -> amount = 200.0000 (ТЕРС ЭМЕС!)
 *     Операциянын көбөгүн тек @Enumerated(STRING) түрү аныктайт.
 *     Себеби: журналда «чыгаруу» деген жазуу 200.0000 салса,
 *     эсептин тездетилген эсептөөсүнө «кайтаруу» үчүн (-amount)
 *     ОЧУР ТАБЫЛТЫЛСЫН, биз болсо эсептөөнүн өзүн чыгарып,
 *     эсептүү кол менен көрсөтөбүз. Өзгөртүүлөбүлбөйт, окууга гана ыңгайлуу.
 *
 * ⚠️ БУЛ КЛАСС API ГА ЧЫГАРЫЛБАЙТ (Entity ≠ DTO эрежеси).
 */
@Entity
@EntityListeners(AuditingEntityListener.class)   // created_at'ы автоматтык толтурат
@Table(name = "transactions")
public class Transaction {

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    // DB: BIGINT GENERATED BY DEFAULT AS IDENTITY
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "account_id", nullable = false)
    // DB: fk_transactions_account FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE RESTRICT
    private Account account;

    @Enumerated(EnumType.STRING)      // ← ЭЧ КАЧАН ORDINAL ЭМЕС (TransactionType.java кара)
    @Column(name = "type", nullable = false, length = 20)
    // DB: VARCHAR(20) + CHECK (type IN ('DEPOSIT','WITHDRAW','TRANSFER_IN','TRANSFER_OUT'))
    private TransactionType type;

    @Column(name = "amount", nullable = false, precision = 19, scale = 4)
    // 🔴 Акча = BigDecimal. DB: NUMERIC(19,4) + CHECK (amount > 0)
    private BigDecimal amount;

    /** Операциядан КИЙИН эсепте канча болгон. Журналда эсеп эмес, «кийинки абал». */
    @Column(name = "balance_after", nullable = false, precision = 19, scale = 4)
    // DB: NUMERIC(19,4) + CHECK (balance_after >= 0)
    private BigDecimal balanceAfter;

    /** Кошумча маалымат: «Cash deposit». Болбосо — null (колонка nullable). */
    @Column(name = "description", length = 500)
    // DB: VARCHAR(500) NULL
    private String description;

    @CreatedDate
    @Column(name = "created_at", nullable = false, updatable = false)
    // DB: TIMESTAMPTZ NOT NULL DEFAULT now()
    private Instant createdAt;

    protected Transaction() {
        // JPA үчүн
    }

    public Transaction(Account account,
                       TransactionType type,
                       BigDecimal amount,
                       BigDecimal balanceAfter,
                       String description) {
        this.account = account;
        this.type = type;
        this.amount = amount;
        this.balanceAfter = balanceAfter;
        this.description = description;
    }

    public Long getId() {
        return id;
    }

    public Account getAccount() {
        return account;
    }

    public TransactionType getType() {
        return type;
    }

    public BigDecimal getAmount() {
        return amount;
    }

    public BigDecimal getBalanceAfter() {
        return balanceAfter;
    }

    public String getDescription() {
        return description;
    }

    public Instant getCreatedAt() {
        return createdAt;
    }
}