package com.minibank.entity;

import java.math.BigDecimal;

import jakarta.persistence.Column;
import jakarta.persistence.Entity;
import jakarta.persistence.FetchType;
import jakarta.persistence.GeneratedValue;
import jakarta.persistence.GenerationType;
import jakarta.persistence.Id;
import jakarta.persistence.JoinColumn;
import jakarta.persistence.ManyToOne;
import jakarta.persistence.Table;

/**
 * accounts таблицасынын Java көрүнүшү.
 *
 * БАЙЛАНЫШ:
 *     users  1 ──────<  accounts
 *   бир колдонуучунун көп эсеби болушу мүмкүн болгон, бирок азыр
 *   бизнес-эреже "бир эсеп" (маалымат базасында UNIQUE(user_id)).
 *
 * 🧡 @ManyToOne(fetch = FetchType.LAZY) эмне үчүн?
 *   Демейде биз АЛТЫН ЭСЕПТИ АЛГАНДА, анын колдонуучусу КЕРЕК ЭМЕС.
 *   LAZY = "кечиктирип алыш: чыныгы керек болгондо гана базадан суроо".
 *   Эгер EAGER болгонда, биз 100 эсеп тизимдесек — 100 КОЛДОНУЧУ
 *   суроосу да жүргөн болмок (N+1 маселеси, кийинки этапта).
 *   LAZY кылсак — эсеп өзи гана окулат, колдонуучу керек болсо
 *   ошол замат гана. Биз булду колдонобуз — бизде @Transactional бар,
 *   ал эс ана өзүнө жабык сессия ачат.
 *
 * ⚠️ БУЛ КЛАСС API ГА ЧЫГАРЫЛБАЙТ (Entity ≠ DTO эрежеси).
 */
@Entity
@Table(name = "accounts")
public class Account extends BaseEntity {

    /** Азырынча банкта бир гана валюта. Кийин USD кошсо — enum кылабыз. */
    public static final String RUB = "RUB";

    /** Акча таажы: 4 байттан кичиси → базада NUMERIC(19,4) менен таптак келиши керек. */
    public static final int BALANCE_SCALE = 4;

    @Id
    @GeneratedValue(strategy = GenerationType.IDENTITY)
    // DB: BIGINT GENERATED BY DEFAULT AS IDENTITY
    private Long id;

    @ManyToOne(fetch = FetchType.LAZY, optional = false)
    @JoinColumn(name = "user_id", nullable = false)
    // DB: fk_accounts_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE RESTRICT
    private User user;

    @Column(name = "account_number", nullable = false, unique = true, length = 34)
    private String accountNumber;

    @Column(name = "currency", nullable = false, length = 3)
    // DB: CHAR(3) + CHECK (currency = 'RUB')
    private String currency;

    @Column(name = "balance", nullable = false, precision = 19, scale = 4)
    // 🔴 БИЗДЕЧИ АКЧА — BigDecimal. ЭЧ КАЧАН double ЭМЕС.
    //    double 0.1 + 0.2 = 0.30000000000000004 деп чыгат.
    //    BigDecimal("0.1").add(BigDecimal("0.2")) = 0.3 (ТУУРА)
    private BigDecimal balance;

    protected Account() {
        // JPA үчүн
    }

    public Account(User user, String accountNumber, String currency, BigDecimal balance) {
        this.user = user;
        this.accountNumber = accountNumber;
        this.currency = currency;
        this.balance = balance;
    }

    /**
     * 💰 АКЧА САЛУУ (deposit): жаңы баланс = көпү + amount.
     *
     * 🧡 ЭМНЕ БУЛ МЕТОД, setBalance() ЭМЕС?
     *     Себеби: «эсеп кантип өзгөрөт» — БИЗНЕС ЭРЕЖЕ. Бул жашыруу
     *     керек: чоң код жыйыгында бир кимдир `account.setBalance(...)`
     *     деп, анын балдарын кечирип жазып коюшун көрсөк, акча
     *     «оңбос кол менен» өзгөрө берет. Биз эсептөөнү ЭСЕПТЕ
     *     гана иштетебиз, чоңкошкон учурда кийин «эмне үчүн?»
     *     деп издегенде, бул жердеги 10 сап жооп берет.
     *
     * @param amount кошулган сумма. Текшерүүлөр Service катматында
     *              (InvalidAmountException) — бул жерде КАЙЧЫК
     *              инвариант: эгер чыныгыдан NullPointer келсе,
     *              катанын түрү өзгөрүшүбөйт, жардам калбайт.
     * @return жаңы баланс (түз дароо эмес, setScale(4) кылынган)
     */
    public BigDecimal credit(BigDecimal amount) {
        this.balance = this.balance.add(amount).setScale(BALANCE_SCALE);
        return this.balance;
    }

    /**
     * 💸 АКЧА ЧЫГАРУУ (withdraw): жаңы баланс = көпү − amount.
     *
     * 🔴 ТЕРС БОЛУШТУГУН БУЛ КЛАСС ЭЛЕ ТЕКШЕРБЕЙТ.
     *     Себеби: «калган акча жетиштиби?» — БИЗНЕС-ЭРЕЖЕ, ошондуктан
     *     ал Service (MoneyService) катматында, InsufficientFundsException
     *     менен текшерилет. Бул жерде биз арифметика гана кылабыз.
     *     Эң акыркы коргоо — маалымат базасындагы
     *     CHECK (balance >= 0) (V1__init.sql).
     */
    public BigDecimal debit(BigDecimal amount) {
        this.balance = this.balance.subtract(amount).setScale(BALANCE_SCALE);
        return this.balance;
    }

    public Long getId() {
        return id;
    }

    public User getUser() {
        return user;
    }

    public String getAccountNumber() {
        return accountNumber;
    }

    public String getCurrency() {
        return currency;
    }

    public BigDecimal getBalance() {
        return balance;
    }
}
