package com.minibank.entity;

/**
 * Акча операциясынын түрү — transactions.type колонкасынын мааниси.
 *
 * 🧠 Эмне үчүн enum, эмес String?
 *     "DEPOSIT" деген сөзүн 40 жерде жазуу — бир күн «DEPOST» деп
 *     жазылып калса, маалымат базасы CHECK ережеси 500 менен чаптап
 *     калмакчы. enum менен: ЖАЗЫП БОЛБОЙТ (компилятор токтотот),
 *     жана биз тийинди катасыз көрсөтөбүз.
 *
 * 🧠 @Enumerated(EnumType.STRING) — Роль.java менен биргеле жаралган:
 *     ORDINAL (0,1,2) салганда, кийин бир түр кошсо, БАРЫКЫ
 *     маалымат базасында жаңы санга жылмайт. Саптак → тынч.
 *
 * 🔴 DB менен ТАПТАК КЕЛИШИ КЕРЕК:
 *     ck_transactions_type CHECK (type IN (...))
 *     V5 миграциясынан кийин базада так ушул төрттүн аты бар.
 *     Биз бул enum'га V-сыны V5 миграциясы жазылды.
 */
public enum TransactionType {

    /** Акча САЛУУ: эсепке кошулду. (PHASE 5) */
    DEPOSIT,

    /** Акча ЧЫГАРУУ: эсептен алынды. (PHASE 5) */
    WITHDRAW,

    /**
     * Башка эсептен БИЗДИН эсебибизге келген акча.
     * 🧡 PHASE 6 (Transfer) иштегэндэ колдонула баштайт.
     *     PHASE 5те аны колдонгон бизнес-логика ЖОК.
     */
    TRANSFER_IN,

    /**
     * БИЗДИН эсебибизден башка эсепке кеткен акча.
     * 🧡 PHASE 6 (Transfer) иштегэндэ колдонула баштайт.
     *     PHASE 5те аны колдонгон бизнес-логика ЖОК.
     */
    TRANSFER_OUT
}