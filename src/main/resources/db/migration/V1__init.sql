-- ---------------------------------------------------------------------
--  USERS — колдонмону колдонуучулар (USER жана ADMIN)
-- ---------------------------------------------------------------------
CREATE TABLE users (
    id            BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name     VARCHAR(150) NOT NULL,
    email         VARCHAR(255) NOT NULL,
    -- BCrypt хэш 60 белги, бирок 255 калдырдык — алгоритм өзгөрсө орун калат
    password_hash VARCHAR(255) NOT NULL,
    role          VARCHAR(20)  NOT NULL DEFAULT 'USER',
    created_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at    TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- UNIQUE -> уникалдык + автоматтык индекс бирге
    CONSTRAINT ux_users_email UNIQUE (email),
    -- Email ДАРИЖИН тамгасыз сакталат. Java да кичирейтип,
    -- DB да "сактап болду" деп карайт (кооптук чек).
    CONSTRAINT ck_users_email_lowercase CHECK (email = lower(email)),
    CONSTRAINT ck_users_role CHECK (role IN ('USER', 'ADMIN'))
);

COMMENT ON TABLE  users               IS 'Колдонмону колдонуучулар';
COMMENT ON COLUMN users.password_hash IS 'BCrypt хэш. Ачык пароль САКТАЛБАЙТ';
COMMENT ON COLUMN users.updated_at    IS 'Java (JPA @LastModifiedDate) жаңартат';

-- ---------------------------------------------------------------------
--  ACCOUNTS — банк эсептери (бир колдонмонунун көп эсеби болушу мүмкүн)
-- ---------------------------------------------------------------------
CREATE TABLE accounts (
    id             BIGINT       GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id        BIGINT       NOT NULL,
    -- IBAN максимум 34 белги -> кийин эл аралык эсеп номуру кошсо деле жетит
    account_number VARCHAR(34)  NOT NULL,
    currency       CHAR(3)      NOT NULL DEFAULT 'RUB',
    -- ⚠️ Акча ҮЧҮН double/float ЭМЕС, NUMERIC. Себеби: 0.1 + 0.2 = 0.30000000000000004
    balance        NUMERIC(19, 4) NOT NULL DEFAULT 0,
    created_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),
    updated_at     TIMESTAMPTZ  NOT NULL DEFAULT now(),

    -- RESTRICT = эсептери бар колдонмонуну ӨЧҮРҮҨГӨ БОЛБОЙТ.
    -- (CASCADE коюлса, колдонмо өчсө эсептери да өчүп кетмекчи)
    CONSTRAINT fk_accounts_user
        FOREIGN KEY (user_id) REFERENCES users (id) ON DELETE RESTRICT,

    CONSTRAINT ux_accounts_account_number UNIQUE (account_number),
    -- Азыр бир гана валюта. USD кошкондо бул CHECK миграция менен кеңейтилет.
    CONSTRAINT ck_accounts_currency CHECK (currency = 'RUB'),
    -- 🔴 КООПСУЗДУК: баланс ТЕРС БОЛУШУ МУМКУН ЭМЕС.
    -- Java'да да текшерем, бирок DB — акыркы коргоо сызыгы.
    CONSTRAINT ck_accounts_balance_non_negative CHECK (balance >= 0)
);

COMMENT ON TABLE  accounts           IS 'Банк эсептери';
COMMENT ON COLUMN accounts.balance   IS 'Акча. NUMERIC(19,4). Терс болушу CHECK менен тыйгат';
COMMENT ON COLUMN accounts.currency  IS 'Азыр RUB гана. Кеңейтүү = V2 миграция';

-- ⚠️ PostgreSQL чет ээ (foreign key) колонкаларына МАТУР АВТОМАТТУК ИНДЕКС ЖАСАБАЙТ
--    (MySQL жасайт). Ошондуктан "колдонмонунун эсептери" деген суроого
--    жооп табуу үчүн индексти ӨЗҮЧҮН кошобуз.
CREATE INDEX ix_accounts_user_id ON accounts (user_id);

-- ---------------------------------------------------------------------
--  TRANSACTIONS — акча операцияларынын журналы (ledger)
--  Бул таблица ЫШАЙТ: жазуу кошулбайт жана ӨЧҮРҮЛБЕЙТ.
-- ---------------------------------------------------------------------
CREATE TABLE transactions (
    id            BIGINT        GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id    BIGINT        NOT NULL,
    type          VARCHAR(20)   NOT NULL,
    amount        NUMERIC(19, 4) NOT NULL,
    -- Операциядан КИЙИН эсепте канча болгон
    balance_after NUMERIC(19, 4) NOT NULL,
    description   VARCHAR(500),
    created_at    TIMESTAMPTZ   NOT NULL DEFAULT now(),

    -- RESTRICT = операциясы бар эсеп ӨЧҮРҮЛБЕЙТ.
    -- CASCADE болсо, эсеп өчкөндө БҮТ АКЧА ЖОГОЛУП КЕТЕК.
    CONSTRAINT fk_transactions_account
        FOREIGN KEY (account_id) REFERENCES accounts (id) ON DELETE RESTRICT,

    CONSTRAINT ck_transactions_type CHECK (type IN ('DEPOSIT', 'WITHDRAW', 'TRANSFER')),
    -- Сумма нөлдөн ЧОҢ болууга тийиш: 0 жана терс сумма мүмкүн эмес
    CONSTRAINT ck_transactions_amount_positive CHECK (amount > 0),
    CONSTRAINT ck_transactions_balance_after_non_negative CHECK (balance_after >= 0)
);

COMMENT ON TABLE  transactions             IS 'Акча операцияларынын журналы. Бир жазуу = бир операция';
COMMENT ON COLUMN transactions.balance_after IS 'Операциядан кийинки эсеп балансы';

-- "Бул эсептин операциялары, эң жаңысы башта" -> эң көп суроо
CREATE INDEX ix_transactions_account_id_created_at
    ON transactions (account_id, created_at DESC);

-- "Бүгүн канча иштеди?" -> ADMINге керек
CREATE INDEX ix_transactions_created_at
    ON transactions (created_at DESC);
