-- =====================================================================
--  Mini Bank — V5 : transactions.type -> PHASE 5 enum менен таптак
-- =====================================================================
--  Себеби (тапшырманын 4-бөлүмү: «Enum database'деги учурдагы
--  constraint менен ТОЛУК шайкеш болсун»):
--
--    V1'де биз жазган CHECK:
--        CHECK (type IN ('DEPOSIT', 'WITHDRAW', 'TRANSFER'))
--
--    PHASE 5 тапшырмасы талап кылган enum:
--        DEPOSIT, WITHDRAW, TRANSFER_IN, TRANSFER_OUT
--
--    «TRANSFER» жалпысы — эки тараптуу которууну БИР типке
--    тыккан абал. Эки эсептин теги жана «кай тарапка» маалыматы
--    КАЙБОЛГОНДУ. Демек биз аны экиге бөлөбүз:
--        TRANSFER_IN  — биздин эсепке КЕЛГЕН (алуучу тарап)
--        TRANSFER_OUT — биздин эсептен КЕТКЕН (берүүчү тарап)
--    Мына ошондуктан CHECK кайра жазылып, ФАКТИКАЛЫК колдонулуучу
--    болгон 4 түргө кеңейтирилди.
--
--  🛡️ КООПСУЗДУК: эң акыркы чеги. Java enum'унда болбогон түр
--     БУГА чыныгы колдонууга БОЛБАЙТ — DB өзү каргайт (check
--     violated -> GlobalExceptionHandler -> 409). Демек кийинки
--     этапта TRANSFER жазып, аны «кай тарап» экенин унутуп
--     калуунун коркуу ЖОК.
--
--  📦 МААЛЫМАТ КЫЙЫНТИ: эң ар кимдеги «TRANSFER» жазуусу
--     жок — PHASE 5ке чейин бул таблица ПУСТ болгон. Ошондуктан
--     маалыматты «көчүрүү» (UPDATE) керек эмес, эң жөнөкөй жол:
--     эски CHECK'ти таштап, жаңысын кошобуз.
-- =====================================================================

ALTER TABLE transactions
    DROP CONSTRAINT ck_transactions_type;

ALTER TABLE transactions
    ADD CONSTRAINT ck_transactions_type
    CHECK (type IN ('DEPOSIT', 'WITHDRAW', 'TRANSFER_IN', 'TRANSFER_OUT'));